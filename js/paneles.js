/* =====================================================
   CAMBIAR IDIOMA
   ===================================================== */

function cambiarIdioma(idioma) {

    if (
        idioma !== "es" &&
        idioma !== "en"
    ) {

        return;

    }


    idiomaActual = idioma;


    mostrarPanel();

}


/* =====================================================
   LEER PANEL
   ===================================================== */

function leerPanel() {

    if (!("speechSynthesis" in window)) {

        alert(
            idiomaActual === "es"
                ? "La lectura de voz no está disponible en este navegador."
                : "Speech synthesis is not available in this browser."
        );

        return;

    }


    const panel = paneles[panelActual];

    if (!panel) {
        return;
    }


    /* Detener cualquier lectura anterior */

    sintesisVoz.cancel();


    const texto =
        panel.texto[idiomaActual];


    if (!texto || texto.trim() === "") {

        return;

    }


    const mensaje =
        new SpeechSynthesisUtterance(texto);


    /* =================================================
       IDIOMA
       ================================================= */

    mensaje.lang =
        idiomaActual === "es"
            ? "es-PE"
            : "en-US";


    /* =================================================
       VELOCIDAD
       ================================================= */

    mensaje.rate = 0.9;

    mensaje.pitch = 1;

    mensaje.volume = 1;


    /* =================================================
       VOZ
       ================================================= */

    const voces =
        sintesisVoz.getVoices();


    let vozSeleccionada = null;


    if (idiomaActual === "es") {

        vozSeleccionada =
            voces.find(
                voz =>
                    voz.lang.toLowerCase() === "es-pe"
            );

        if (!vozSeleccionada) {

            vozSeleccionada =
                voces.find(
                    voz =>
                        voz.lang
                            .toLowerCase()
                            .startsWith("es")
                );

        }

    } else {

        vozSeleccionada =
            voces.find(
                voz =>
                    voz.lang.toLowerCase() === "en-us"
            );

        if (!vozSeleccionada) {

            vozSeleccionada =
                voces.find(
                    voz =>
                        voz.lang
                            .toLowerCase()
                            .startsWith("en")
                );

        }

    }


    if (vozSeleccionada) {

        mensaje.voice =
            vozSeleccionada;

    }


    /* =================================================
       CUANDO COMIENZA
       ================================================= */

    mensaje.onstart = function () {

        hablando = true;

        actualizarBotonLeer();

    };


    /* =================================================
       CUANDO TERMINA
       ================================================= */

    mensaje.onend = function () {

        hablando = false;

        actualizarBotonLeer();

    };


    /* =================================================
       ERROR
       ================================================= */

    mensaje.onerror = function () {

        hablando = false;

        actualizarBotonLeer();

    };


    /* =================================================
       REPRODUCIR
       ================================================= */

    sintesisVoz.speak(mensaje);

}


